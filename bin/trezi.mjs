#!/usr/bin/env bun

// `trezi --update`: pull, reinstall and rebuild this checkout. The `trezi` command
// itself is the shell script beside this file (bin/trezi), which runs this with the
// Bun on PATH or the one bundled into Trezi.app. Any other arguments are handed to
// bin/trezi, for installs whose `trezi` link still points here.
import { execFileSync, spawnSync } from 'node:child_process'
import { realpathSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { requireSupportedPlatform } from '../scripts/requirements.mjs'

const repoRoot = dirname(dirname(fileURLToPath(import.meta.url)))

// Lockfiles are regenerated by the package manager as a side effect of
// `install`, so a checkout that's been built or updated once carries a dirty,
// machine-authored lockfile. That drift makes `git pull --ff-only` abort with
// "local changes would be overwritten by merge" — the exact failure users hit
// running `trezi --update`. Since the update reinstalls right after pulling
// (regenerating the lockfile against the new package.json), it's safe to
// discard the drift first. Kept as a pure helper so it's unit-testable.
const LOCKFILES = new Set([
  'bun.lock',
  'bun.lockb',
  'package-lock.json',
  'npm-shrinkwrap.json',
  'yarn.lock',
  'pnpm-lock.yaml',
])

/**
 * Given `git status --porcelain` output, return the tracked lockfiles that are
 * dirty (staged and/or unstaged) and should be restored to HEAD before a pull.
 * Untracked ('??') entries are ignored — there's nothing at HEAD to restore.
 */
export function lockfilesToRestore(porcelain) {
  const restore = []
  for (const line of String(porcelain).split('\n')) {
    if (line.length < 4) continue
    const status = line.slice(0, 2)
    if (status === '??') continue
    // porcelain paths start at column 3; renames read "old -> new" (not a
    // lockfile concern, but take the post-rename path if it ever occurs).
    const raw = line.slice(3).trim()
    const path = raw.includes(' -> ') ? raw.slice(raw.indexOf(' -> ') + 4) : raw
    if (LOCKFILES.has(path)) restore.push(path)
  }
  return restore
}

/** The Bun on PATH, else the one running this (Trezi's bundled Bun). */
function bun() {
  const check = spawnSync('bun', ['--version'], { stdio: 'ignore' })
  return check.error || check.status !== 0 ? process.execPath : 'bun'
}

function update() {
  requireSupportedPlatform()
  let before
  try {
    before = execFileSync('git', ['rev-parse', '--short', 'HEAD'], {
      cwd: repoRoot,
    })
      .toString()
      .trim()
  } catch {
    console.error('Could not determine current git revision.')
    process.exit(1)
  }

  // Drop machine-generated lockfile drift so `git pull --ff-only` doesn't abort
  // on it; `install` below rebuilds the lockfile against the pulled package.json.
  const status = spawnSync('git', ['status', '--porcelain'], {
    cwd: repoRoot,
    encoding: 'utf8',
  })
  if (status.status === 0) {
    const dirtyLocks = lockfilesToRestore(status.stdout)
    if (dirtyLocks.length > 0) {
      console.log(
        `Discarding local ${dirtyLocks.join(', ')} changes (regenerated on install)…`,
      )
      spawnSync('git', ['checkout', 'HEAD', '--', ...dirtyLocks], {
        cwd: repoRoot,
        stdio: 'inherit',
      })
    }
  }

  const pm = bun()
  const steps = [
    ['git', ['pull', '--ff-only']],
    [pm, ['install']],
    [pm, ['run', 'build']],
  ]

  for (const [cmd, args] of steps) {
    const result = spawnSync(cmd, args, { cwd: repoRoot, stdio: 'inherit' })
    if (result.status !== 0) {
      console.error(
        `Update failed while running \`${cmd === pm ? 'bun' : cmd} ${args.join(' ')}\` (exit code ${result.status}).` +
          (cmd === 'git'
            ? ' If you have local changes, commit or stash them and try again.'
            : ''),
      )
      process.exit(result.status ?? 1)
    }
  }

  const after = execFileSync('git', ['rev-parse', '--short', 'HEAD'], {
    cwd: repoRoot,
  })
    .toString()
    .trim()

  if (before === after) {
    console.log('Trezi is already up to date.')
  } else {
    console.log(`Updated ${before} → ${after}.`)
  }

  console.log('Run `trezi` to (re)start.')
  process.exit(0)
}

function main() {
  const args = process.argv.slice(2)
  // --no-launch (older in-app updaters pass it) is accepted and ignored.
  if (args[0] === '--update' || args[0] === 'update') return update()
  const result = spawnSync(join(repoRoot, 'bin/trezi'), args, { stdio: 'inherit' })
  process.exit(result.status ?? 1)
}

// Run the CLI only when invoked as a script (directly or via a PATH symlink), not
// when imported by a test. realpath both sides so the symlink and its target compare
// equal. Default to running on any error — a real CLI invocation always has a
// resolvable argv[1], so a throw here only happens in edge cases where no-op'ing the
// command would be worse.
function invokedAsScript() {
  try {
    return realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url))
  } catch {
    return true
  }
}

if (invokedAsScript()) {
  try { main() } catch (error) { console.error(error.message); process.exitCode = 1 }
}
